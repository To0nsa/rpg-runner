/// Renders validated source into typed Core definitions, append-only enums and
/// shared presentation. The caller owns captured I/O and atomic publication.
List<GeneratedArtifact> buildItemArtifacts(ItemCatalogSource catalog) {
  requireItemRuntimeCompatibility(catalog);
  final artifacts = <GeneratedArtifact>[];
  catalog.validatePresentation(canonicalItemIconChoices);
  const header =
      '// GENERATED by tool/item_generation.dart. Do not edit.\n// Source: assets/authoring/items/item_defs.json\n';
  for (final category in ItemCategory.values) {
    final entries = catalog.items.where((i) => i.category == category).toList();
    final ids = {
      for (final item in entries) item.ordinal: item.id,
      if (category == ItemCategory.projectile) ...catalog.internalProjectiles,
    };
    final ordinals = ids.keys.toList()..sort();
    var identity =
        '${header}enum ${category.enumType} {\n${[for (final n in ordinals) '${ids[n]},'].join('\n')}\n}\n';
    if (category == ItemCategory.projectile) {
      identity +=
          '\nconst playerEquippableProjectileIds = <ProjectileId>[\n${entries.map((i) => '  ProjectileId.${i.id},').join('\n')}\n];\n';
      identity +=
          '\nconst hunterRangedWeaponIds = <ProjectileId>[${entries.where((i) => i.family!.name == 'firearm' || i.family!.name == 'crossbow').map((i) => 'ProjectileId.${i.id},').join('\n')}];\n';
      identity +=
          '\n/// Canonical render/muzzle profile; item physics and payload keep their own ID.\nProjectileId projectileRenderSource(ProjectileId id) => const <ProjectileId,ProjectileId>{${entries.map((i) => 'ProjectileId.${i.id}:ProjectileId.${i.renderAs},').join('\n')}}[id] ?? id;\n';
    }
    artifacts.add(
      GeneratedArtifact(
        path:
            'packages/runner_core/lib/${category.folder}/${category.fileStem}_id.dart',
        content: identity,
      ),
    );
    final imports = [
      '../abilities/ability_def.dart',
      '../combat/damage_type.dart',
      '../combat/status/status.dart',
      '../stats/gear_stat_bonuses.dart',
      '../weapons/weapon_proc.dart',
      '../weapons/reactive_proc.dart',
      '${category.fileStem}_id.dart',
      category == ItemCategory.projectile
          ? 'projectile_item_def.dart'
          : '${category.fileStem}_def.dart',
      if (category == ItemCategory.weapon) 'weapon_category.dart',
    ];
    // Unused import suppression is limited to this generated closed schema: new
    // values can use any supported field without hand-editing the import list.
    final content =
        '$header// ignore_for_file: unused_import\n${imports.map((i) => "import '$i';").join('\n')}\n'
        'const authored${category.enumType}Definitions = <${category.enumType},${category.constructor}>{\n'
        '${entries.map((i) => '${category.enumType}.${i.id}: ${category.constructor}(id:${category.enumType}.${i.id},${renderItemFields(i.data, itemFields(category))}),').join('\n')}\n};\n';
    artifacts.add(
      GeneratedArtifact(
        path:
            'packages/runner_core/lib/${category.folder}/${category.fileStem}_data.generated.dart',
        content: content,
      ),
    );
  }
  String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
  final presentation = StringBuffer(
    '$header'
    "import 'item_icon_ids.dart';\n",
  );
  for (final category in ItemCategory.values) {
    presentation.writeln(
      "import 'package:runner_core/${category.folder}/${category.fileStem}_id.dart';",
    );
  }
  presentation.writeln('const _names = <String,Map<String,String>>{');
  for (final i in catalog.items) {
    presentation.writeln(
      '${literal(i.key)}:{${i.names.entries.map((e) => '${literal(e.key)}:${literal(e.value)},').join()}},',
    );
  }
  presentation.writeln(
    '};\nString? authoredItemName(String category,String id,String locale) => _names["\$category/\$id"]?[locale.split("_").first] ?? _names["\$category/\$id"]?["en"];',
  );
  for (final category in ItemCategory.values) {
    final type = category.enumType.replaceAll('Id', '');
    final nullable = category == ItemCategory.projectile;
    presentation.writeln(
      'Canonical${type}Icon${nullable ? '?' : ''} itemIconFor$type(${category.enumType} id) => const <${category.enumType},Canonical${type}Icon>{',
    );
    for (final i in catalog.items.where((i) => i.category == category)) {
      presentation.writeln(
        '${category.enumType}.${i.id}:Canonical${type}Icon.${i.icon},',
      );
    }
    presentation.writeln('}[id]${nullable ? '' : '!'};');
  }
  artifacts.add(
    GeneratedArtifact(
      path: 'packages/game_presentation/lib/items.generated.dart',
      content: presentation.toString(),
    ),
  );
  return artifacts;
}

/// Generation enforces the same non-migrating identity contract as Save, even
/// when source JSON was changed outside the editor. Current compiled Core is
/// the retained-ID baseline; new identities may only append.
void requireItemRuntimeCompatibility(ItemCatalogSource catalog) {
  if (catalog.internalProjectiles.length !=
      ProjectileId.values
          .where((id) => !playerEquippableProjectileIds.contains(id))
          .length) {
    throw const FormatException(
      'Internal projectile membership is code-owned.',
    );
  }
  for (final category in ItemCategory.values) {
    final List<Enum> ids = switch (category) {
      ItemCategory.weapon => WeaponId.values,
      ItemCategory.accessory => AccessoryId.values,
      ItemCategory.spellBook => SpellBookId.values,
      ItemCategory.projectile => ProjectileId.values,
    };
    for (final id in ids) {
      if (category == ItemCategory.projectile &&
          !playerEquippableProjectileIds.contains(id)) {
        if (catalog.internalProjectiles[id.index] != id.name) {
          throw FormatException('Internal projectile ${id.name} is reserved.');
        }
        continue;
      }
      final item = catalog.items.where((i) => i.id == id.name).firstOrNull;
      if (item == null ||
          item.category != category ||
          item.ordinal != id.index) {
        throw FormatException(
          '${id.name}: Existing IDs, category and ordinals are immutable.',
        );
      }
      if (id is WeaponId) {
        final old = const WeaponCatalog().get(id);
        if (item.family != old.weaponType ||
            item.data['category'] != old.category.name ||
            (item.data['isTwoHanded'] ?? false) != old.isTwoHanded) {
          throw FormatException(
            '${id.name}: Eligibility/slot changes require a separately reviewed saved-loadout migration. Duplicate instead.',
          );
        }
      } else if (id is SpellBookId) {
        if (item.family != const SpellBookCatalog().get(id).weaponType) {
          throw FormatException(
            '${id.name}: Equipment family is compatibility-locked.',
          );
        }
      } else if (id is ProjectileId) {
        if (item.family != const ProjectileCatalog().get(id).weaponType) {
          throw FormatException(
            '${id.name}: Equipment family is compatibility-locked.',
          );
        }
      }
    }
  }
}
