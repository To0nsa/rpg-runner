part of 'generate_chunk_runtime_data.dart';

/// A single atomic build emits client, Core and server projections. The digest
/// binds mission policy and the captured transitive content dependency closure.
List<GeneratedArtifact> buildCampaignArtifacts(
  ContentBuildSnapshot inputs,
  Set<String> levels,
  Set<String> themes,
) {
  if (!inputs.contains(campaignSourcePath)) {
    // Minimal generator workspaces still compile GameCore without enabling missions.
    return [
      GeneratedArtifact(
        path: 'packages/runner_core/lib/campaign/campaign_registry.dart',
        content:
            "// GENERATED FILE. DO NOT EDIT BY HAND.\n// Generated by tool/generate_chunk_runtime_data.dart\n"
            "import 'campaign_mission_definition.dart';\n"
            "const campaignRegionalLevelIds = <String, String>{};\n"
            "const campaignContentDigest = '${'0' * 64}';\n"
            "final campaignMissions = Map<String, CampaignMissionDefinition>.unmodifiable({});\n",
      ),
    ];
  }
  final catalog = CampaignCatalogSource.decode(
    inputs.readString(campaignSourcePath),
  );
  final chunkTexts = <String, String>{};
  for (final path in inputs.files.keys.where(
    (p) => p.startsWith('$_chunksDirectoryPath/') && p.endsWith('.json'),
  )) {
    final text = inputs.readString(path);
    final chunk = decodePolygonTerrainChunk(text, sourcePath: path);
    chunkTexts[chunk.chunkKey] = text;
  }
  final included = <CompiledCampaignMission>[];
  for (final mission in catalog.missions) {
    if (!levels.contains(mission.levelId) ||
        !themes.contains(mission.visualThemeId)) {
      throw FormatException('${mission.id}: unknown level or visual theme.');
    }
    if (mission.includeInBuild) {
      included.add(
        compileCampaignMission(
          source: mission,
          chunkContentsByKey: chunkTexts,
          prefabContents: inputs.readString(_prefabDefsPath),
          tileContents: inputs.readString(_tileDefsPath),
        ),
      );
    }
  }
  final dependencies = <String, Object?>{
    'catalog': catalog.toJson(),
    'prefabs': inputs.files[_prefabDefsPath],
    'tiles': inputs.files[_tileDefsPath],
    'materials':
        inputs.files['assets/authoring/level/terrain_material_defs.json'],
    'chunks': {
      for (final key
          in (included
              .expand((m) => m.source.route.map((o) => o.chunkKey))
              .toSet()
              .toList()
            ..sort()))
        key: sha256.convert(utf8.encode(chunkTexts[key]!)).toString(),
    },
  };
  final digest = sha256
      .convert(utf8.encode(jsonEncode(dependencies)))
      .toString();
  final projection = {
    'contentDigest': digest,
    'rewardPolicyVersion': 1,
    'chapters': [
      for (final chapter in catalog.chapters)
        {
          'id': chapter.id,
          'title': chapter.title,
          'description': chapter.description,
          'mapX': chapter.mapX,
          'mapY': chapter.mapY,
          'rewardCharacterId': chapter.rewardCharacterId,
          'rewardXp': chapter.rewardXp,
          'rewardGold': chapter.rewardGold,
          'rewardItems': chapter.rewardItems
              .map((item) => item.toJson())
              .toList(),
          'missions': [
            for (final mission in chapter.missions)
              {
                'id': mission.id,
                'revision': mission.revision,
                'available': mission.includeInBuild,
                'title': mission.title,
                'description': mission.description,
                'levelId': mission.levelId,
                'firstClearXp': mission.firstClearXp,
                'rewardAbilityId': mission.rewardAbilityId,
              },
          ],
        },
    ],
  };
  const header =
      '// GENERATED FILE. DO NOT EDIT BY HAND.\n// Generated by tool/generate_chunk_runtime_data.dart\n';
  final chunks = <String, PolygonTerrainRuntimeChunk>{
    for (final mission in included)
      for (final chunk in mission.chunks) chunk.pattern.chunkKey!: chunk,
  };
  final ordered = chunks.values.toList()
    ..sort((a, b) => a.pattern.chunkKey!.compareTo(b.pattern.chunkKey!));
  final buffer = StringBuffer(header)
    ..writeln("import 'campaign_mission_definition.dart';");
  if (ordered.isNotEmpty) {
    buffer
      ..writeln("import '../track/chunk_pattern.dart';")
      ..writeln("import '../track/chunk_pattern_source.dart';")
      ..writeln("import '../track/finite_chunk_pattern_source.dart';")
      ..writeln("import 'authored_campaign_terrain.dart';");
    if (ordered.any(
      (c) =>
          c.pattern.spawnMarkers.isNotEmpty ||
          c.pattern.encounters.isNotEmpty ||
          c.pattern.bossArena != null,
    ))
      buffer.writeln("import '../enemies/enemy_id.dart';");
    if (ordered.any((c) => c.pattern.bossArena != null))
      buffer.writeln("import '../bosses/boss_arena_definition.dart';");
    if (ordered.any((c) => c.pattern.encounters.isNotEmpty))
      buffer
        ..writeln("import '../combat/ai_target_policy.dart';")
        ..writeln("import '../encounters/encounter_definition.dart';")
        ..writeln("import '../npcs/npc_id.dart';");
    if (ordered.any(
      (c) => c.pattern.traps.isNotEmpty || c.pattern.encounters.isNotEmpty,
    ))
      buffer.writeln("import '../snapshots/enums.dart';");
    if (ordered.any((c) => c.pattern.traps.isNotEmpty))
      buffer
        ..writeln("import '../traps/trap_id.dart';")
        ..writeln("import '../traps/trap_geometry.dart';")
        ..writeln("import '../traps/trap_placement.dart';");
    _writePatternList(buffer, '_chunks', [
      for (final chunk in ordered)
        _ChunkExportData(
          path: chunk.sourcePath,
          levelId: chunk.stagedTerrain.levelId,
          difficulty: chunk.stagedTerrain.difficulty,
          isRuntimeEligible: true,
          pattern: chunk.pattern,
        ),
    ]);
  }
  buffer
    ..writeln(
      "const campaignRegionalLevelIds = <String, String>{${included.map((mission) => "'${mission.source.id}': '${mission.source.levelId}'").join(',')}};",
    )
    ..writeln("const campaignContentDigest = '$digest';")
    ..writeln(
      'final campaignMissions = Map<String, CampaignMissionDefinition>.unmodifiable({',
    );
  String point(CampaignPoint p) =>
      "CampaignPoint(occurrenceId: '${_escape(p.occurrenceId)}', x: ${p.x}, y: ${p.y})";
  String region(CampaignRegion r) =>
      'CampaignRegion(origin: ${point(r.origin)}, width: ${r.width}, height: ${r.height})';
  for (final mission in included) {
    final m = mission.source;
    buffer
      ..writeln(
        "'${m.id}': CampaignMissionDefinition(id: '${m.id}', visualThemeId: '${m.visualThemeId}',",
      )
      ..writeln(
        'terrainChunks: stagedAuthoredTerrain.chunks, combatAllowed: ${m.combatAllowed},',
      )
      ..writeln('route: FiniteChunkPatternSource([');
    for (final o in m.route) {
      final index = ordered.indexWhere((c) => c.pattern.chunkKey == o.chunkKey);
      buffer.writeln(
        "FiniteChunkOccurrence(id: '${o.id}', sourceLevelId: '${o.levelId}', pattern: _chunks[$index], tier: ChunkPatternTier.${ordered[index].stagedTerrain.difficulty}),",
      );
    }
    buffer
      ..writeln(']), start: ${point(m.start!)}, exit: ${region(m.exit!)},')
      ..writeln('collectibles: [${m.collectibles.map(point).join(',')}],')
      ..writeln(
        'requiredRegions: [${m.requiredRegions.map(region).join(',')}],',
      )
      ..writeln(
        "requiredEnemies: [${m.requiredEnemies.map((e) => "(occurrenceId: '${e.occurrenceId}', markerSalt: ${e.markerSalt})").join(',')}],",
      )
      ..writeln(
        "requiredRescues: [${m.requiredRescues.map((e) => "(occurrenceId: '${e.occurrenceId}', encounterId: '${e.encounterId}')").join(',')}],",
      )
      ..writeln('),');
  }
  buffer.writeln('});');
  // Mission compilation checked exact adjacency, including cross-owner joins.
  // This batch validates stable chunk records for rendering without inventing a
  // runner scheduler or a loop from the finite exit back to its entrance.
  final batch = ordered.isEmpty
      ? null
      : validatePolygonTerrainSeams(
          chunks: ordered.map((c) => c.compiled),
          manifest: PolygonTerrainSeamManifest(
            sourcePath: campaignSourcePath,
            signature: TerrainAuthoringSeamSignature([]),
          ),
        ).batch!;
  return [
    GeneratedArtifact(
      path: 'packages/runner_core/lib/campaign/campaign_registry.dart',
      content: buffer.toString(),
    ),
    if (batch != null)
      GeneratedArtifact(
        path:
            'packages/runner_core/lib/campaign/authored_campaign_terrain.dart',
        content: renderStagedPolygonTerrainDart(batch),
      ),
    GeneratedArtifact(
      path: 'lib/ui/campaign/generated_campaign_catalog.dart',
      content:
          '${header}const Map<String, Object?> campaignCatalogData = ${const JsonEncoder.withIndent('  ').convert(projection).replaceAll(r'$', r'\$')};\n',
    ),
    GeneratedArtifact(
      path: 'functions/src/campaign/generated_catalog.ts',
      content:
          '${header}export const campaignCatalog = ${const JsonEncoder.withIndent('  ').convert(projection)} as const;\n',
    ),
  ];
}
