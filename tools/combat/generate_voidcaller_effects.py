"""Generate beam part source rectangles from the imported PNG; --check checks drift.

Only source pixels are inspected. Destination geometry is reviewed in source
pixels at 1.5x scale, matching VoidcallerPoseCatalog's world-space beams.
"""
import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile
from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--dart', default=shutil.which('dart'))
    args = parser.parse_args()
    if not args.dart:
        parser.error('Dart SDK executable missing; provide --dart.')
    root = Path(__file__).resolve().parents[2]
    (root / '.tmp').mkdir(exist_ok=True)
    image = Image.open(root / 'assets/images/entities/enemies/ancient_god_pack/voidcaller/sprite_sheet.png').convert('RGBA')

    def part(row, column, offset_x, offset_y, crop_top=None, crop_height=None):
        tile = image.crop((column*171,row*136,(column+1)*171,(row+1)*136))
        x0,y0,x1,y1 = tile.getchannel('A').getbbox()
        if crop_top is not None:
            y0,y1 = crop_top,crop_top+crop_height
        width,height = x1-x0,y1-y0
        return f'RenderFramePart(source: RenderFrameRect({column*171+x0}, {row*136+y0}, {width}, {height}), position: Vec2({x0+offset_x:g}, {y0+offset_y:g}), size: Vec2({width}, {height}))'

    lines = ["// Generated by tools/combat/generate_voidcaller_effects.py; do not edit.","import '../contracts/render_anim_set_definition.dart';", "import '../contracts/render_frame_part.dart';", "import '../contracts/render_frame_rect.dart';", "import '../snapshots/enums.dart';", "import '../util/vec2.dart';", '', '/// Portal, beam and surface impact share the twelve-frame damage clock.', 'abstract final class VoidcallerEffectCatalog {']
    for diagonal in [False,True]:
        name = 'diagonal' if diagonal else 'vertical'
        startup,ground,portal = (10,13,14) if diagonal else (5,8,9)
        # Fixed source-cell pivots preserve the beam axis as debris animates.
        # Diagonal source pixels descend left by one pixel per two rows.
        target_x = 46 if diagonal else 92
        center = target_x + 60 if diagonal else target_x
        lines += [f'  static const {name} = RenderAnimSetDefinition(', f'    frameWidth: 138, frameHeight: 146, anchorPoint: Vec2({target_x},146),', "    sourcesByKey: {AnimKey.hit: 'entities/enemies/ancient_god_pack/voidcaller/sprite_sheet.png'},", '    frameCountsByKey: {AnimKey.hit: 12}, stepTimeSecondsByKey: {AnimKey.hit: .08},', '    compositeFramesByKey: {AnimKey.hit: [']
        for frame in range(12):
            if frame<5:
                axis = 94 if diagonal else 83
                top_offset = -76 if diagonal else -83
                parts = [part(startup,frame,center-axis,top_offset),
                         part(startup,frame,target_x-(78 if diagonal else 83),12)]
            else:
                phase=min(frame-5,5)
                axis = 94 if diagonal else 83
                top_offset = -76 if diagonal else -83
                parts=[part(portal,phase,center-axis,top_offset)]
                if frame<10:
                    # Tile native strips at integer positions: no rotation or
                    # rescaling that changes width/slope at an endcap join.
                    start,end = (58,114) if diagonal else (51,121)
                    row,source_top = (12,102) if diagonal else (7,77)
                    for y in range(start,end,32):
                        x = center-(y-26)/2 if diagonal else center
                        parts += [part(row,phase%2,x-axis,y-source_top,
                                       source_top,min(32,end-y))]
                ground_axis = 78 if diagonal else 83
                parts += [part(ground,phase,target_x-ground_axis,12)]
            lines.append('      ['+', '.join(parts)+'],')
        lines += ['    ]},','  );']
    lines += ['}']
    target=root/'packages/runner_core/lib/spell_impacts/voidcaller_effect_catalog.dart'
    with tempfile.TemporaryDirectory(dir=root/'.tmp') as directory:
        output=Path(directory)/target.name
        output.write_text('\n'.join(lines)+'\n',encoding='utf8')
        subprocess.run([args.dart,'--suppress-analytics','format',str(output)],check=True)
        content=output.read_text(encoding='utf8')
    if args.check:
        if target.read_text(encoding='utf8')!=content:
            raise SystemExit('Voidcaller beam metadata is stale.')
        print('Voidcaller beam metadata is current.')
    else:
        target.write_text(content,encoding='utf8')


if __name__=='__main__':
    main()
